-- InternFlow - Stage 3.1 core schema.
--
-- Scope: the six entities required by Stage 3.1:
--   users, cohorts, cohort_memberships, cohort_coordinator_assignments,
--   companies, internships.
--
-- Deliberately NOT created here (later substages / still-open decisions):
--   cohort_requirements (OD-03), weekly_reports and report_events (OD-02/OD-10),
--   documents/document_reviews (OD-05/OD-16), requirement_evaluations (OD-04),
--   completion_verifications (OD-08), notifications (OD-09), audit_events (OD-06).
-- Keeping them out of this migration is what allows Stage 3.1 to proceed while
-- OD-02 and OD-03 remain unresolved.
--
-- Conventions follow docs/architecture/DDD.md section 2.1:
--   snake_case plural tables and columns, bigint identity primary keys,
--   timestamptz, text + CHECK constraints for enumerations,
--   foreign keys <referenced_table>_id, ON DELETE RESTRICT everywhere.
--
-- Physical and scope decisions implemented here are recorded in
-- docs/architecture/DECISIONS.md (IF-DEC-20, IF-DEC-21, IF-DEC-22) and
-- docs/architecture/DDD.md section 15.

-- ---------------------------------------------------------------------------
-- users
-- Single role per user (AS-04) and a single enumerated role column: there is
-- deliberately no roles/permissions table (DDD section 3; IF-DEC-19).
-- ---------------------------------------------------------------------------
CREATE TABLE users (
    id                      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    identity                TEXT        NOT NULL,
    display_name            TEXT        NOT NULL,
    role                    TEXT        NOT NULL,
    account_status          TEXT        NOT NULL DEFAULT 'ACTIVE',
    activation_state        TEXT        NOT NULL DEFAULT 'PENDING',
    credential_hash         TEXT,
    must_change_password    BOOLEAN     NOT NULL DEFAULT TRUE,
    contact_email           TEXT,
    contact_phone           TEXT,
    created_at              TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at              TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT uq_users_identity UNIQUE (identity),
    CONSTRAINT ck_users_identity_normalized
        CHECK (identity = lower(btrim(identity)) AND char_length(identity) <= 254),
    CONSTRAINT ck_users_display_name
        CHECK (btrim(display_name) <> '' AND char_length(display_name) <= 200),
    CONSTRAINT ck_users_role
        CHECK (role IN ('STUDENT', 'FACULTY_COORDINATOR', 'COLLEGE_ADMINISTRATOR')),
    CONSTRAINT ck_users_account_status
        CHECK (account_status IN ('ACTIVE', 'DEACTIVATED')),
    CONSTRAINT ck_users_activation_state
        CHECK (activation_state IN ('PENDING', 'ACTIVATED'))
);

COMMENT ON TABLE users IS
    'Accounts, one MVP role per user, activation and account status (DDD 4.1; IF-DEC-19).';
COMMENT ON COLUMN users.identity IS
    'Email address used as login identity; stored trimmed/lowercase (IF-DEC-19).';
COMMENT ON COLUMN users.credential_hash IS
    'BCrypt hash; never exposed through the API, logs, or audit payloads.';
COMMENT ON COLUMN users.must_change_password IS
    'IF-DEC-19: administrator-set temporary password must be changed at first sign-in.';

-- ---------------------------------------------------------------------------
-- cohorts
-- ---------------------------------------------------------------------------
CREATE TABLE cohorts (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cohort_code      TEXT        NOT NULL,
    name             TEXT        NOT NULL,
    period_start     DATE,
    period_end       DATE,
    deadline_config  JSONB,
    status           TEXT        NOT NULL DEFAULT 'ACTIVE',
    created_at       TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at       TIMESTAMPTZ NOT NULL DEFAULT now(),
    created_by       BIGINT,
    updated_by       BIGINT,
    CONSTRAINT uq_cohorts_code UNIQUE (cohort_code),
    CONSTRAINT ck_cohorts_code
        CHECK (btrim(cohort_code) <> '' AND char_length(cohort_code) <= 50),
    CONSTRAINT ck_cohorts_name
        CHECK (btrim(name) <> '' AND char_length(name) <= 200),
    CONSTRAINT ck_cohorts_status
        CHECK (status IN ('ACTIVE', 'INACTIVE')),
    CONSTRAINT ck_cohorts_period_paired
        CHECK ((period_start IS NULL) = (period_end IS NULL)),
    CONSTRAINT ck_cohorts_period_order
        CHECK (period_start IS NULL OR period_end >= period_start),
    CONSTRAINT fk_cohorts_created_by
        FOREIGN KEY (created_by) REFERENCES users (id) ON DELETE RESTRICT,
    CONSTRAINT fk_cohorts_updated_by
        FOREIGN KEY (updated_by) REFERENCES users (id) ON DELETE RESTRICT
);

COMMENT ON TABLE cohorts IS
    'Cohort identity, applicable period, deadline configuration and lifecycle status (DDD 4.2).';
COMMENT ON COLUMN cohorts.deadline_config IS
    'Opaque configuration until OD-10 defines deadline keys and semantics; no values are invented.';

-- ---------------------------------------------------------------------------
-- cohort_memberships
-- AS-02 working assumption: at most one active membership per student.
-- ---------------------------------------------------------------------------
CREATE TABLE cohort_memberships (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    student_user_id  BIGINT      NOT NULL,
    cohort_id        BIGINT      NOT NULL,
    joined_at        TIMESTAMPTZ NOT NULL DEFAULT now(),
    left_at          TIMESTAMPTZ,
    created_by       BIGINT,
    CONSTRAINT fk_cohort_memberships_student
        FOREIGN KEY (student_user_id) REFERENCES users (id) ON DELETE RESTRICT,
    CONSTRAINT fk_cohort_memberships_cohort
        FOREIGN KEY (cohort_id) REFERENCES cohorts (id) ON DELETE RESTRICT,
    CONSTRAINT fk_cohort_memberships_created_by
        FOREIGN KEY (created_by) REFERENCES users (id) ON DELETE RESTRICT,
    CONSTRAINT ck_cohort_memberships_period
        CHECK (left_at IS NULL OR left_at >= joined_at)
);

CREATE UNIQUE INDEX uq_cohort_memberships_active_student
    ON cohort_memberships (student_user_id)
    WHERE left_at IS NULL;

CREATE INDEX ix_cohort_memberships_cohort_joined
    ON cohort_memberships (cohort_id, joined_at);

COMMENT ON TABLE cohort_memberships IS
    'Student-to-cohort assignment; active membership is left_at IS NULL (FR-COHORT-002; AS-02).';

-- ---------------------------------------------------------------------------
-- cohort_coordinator_assignments
-- AS-03 working assumption: one active primary coordinator per cohort;
-- additional non-primary coordinators remain supported (FR-COHORT-003).
-- ---------------------------------------------------------------------------
CREATE TABLE cohort_coordinator_assignments (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cohort_id         BIGINT      NOT NULL,
    faculty_user_id   BIGINT      NOT NULL,
    is_primary        BOOLEAN     NOT NULL DEFAULT FALSE,
    assigned_at       TIMESTAMPTZ NOT NULL DEFAULT now(),
    assigned_by       BIGINT,
    unassigned_at     TIMESTAMPTZ,
    CONSTRAINT fk_cohort_coordinators_cohort
        FOREIGN KEY (cohort_id) REFERENCES cohorts (id) ON DELETE RESTRICT,
    CONSTRAINT fk_cohort_coordinators_faculty
        FOREIGN KEY (faculty_user_id) REFERENCES users (id) ON DELETE RESTRICT,
    CONSTRAINT fk_cohort_coordinators_assigned_by
        FOREIGN KEY (assigned_by) REFERENCES users (id) ON DELETE RESTRICT,
    CONSTRAINT ck_cohort_coordinators_period
        CHECK (unassigned_at IS NULL OR unassigned_at >= assigned_at)
);

CREATE UNIQUE INDEX uq_cohort_coordinators_active_assignment
    ON cohort_coordinator_assignments (cohort_id, faculty_user_id)
    WHERE unassigned_at IS NULL;

CREATE UNIQUE INDEX uq_cohort_coordinators_active_primary
    ON cohort_coordinator_assignments (cohort_id)
    WHERE is_primary AND unassigned_at IS NULL;

CREATE INDEX ix_cohort_coordinators_faculty_active
    ON cohort_coordinator_assignments (faculty_user_id)
    WHERE unassigned_at IS NULL;

COMMENT ON TABLE cohort_coordinator_assignments IS
    'Faculty Coordinator record-scope assignment; removal sets unassigned_at (FR-COHORT-003; AS-03).';

-- ---------------------------------------------------------------------------
-- companies
-- Stage 3 addition (IF-DEC-21). Minimal reference entity: no contact,
-- industry, location or mentor fields are invented.
-- ---------------------------------------------------------------------------
CREATE TABLE companies (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name        TEXT        NOT NULL,
    status      TEXT        NOT NULL DEFAULT 'ACTIVE',
    created_at  TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at  TIMESTAMPTZ NOT NULL DEFAULT now(),
    created_by  BIGINT,
    updated_by  BIGINT,
    CONSTRAINT ck_companies_name
        CHECK (btrim(name) <> '' AND char_length(name) <= 200),
    CONSTRAINT ck_companies_status
        CHECK (status IN ('ACTIVE', 'INACTIVE')),
    CONSTRAINT fk_companies_created_by
        FOREIGN KEY (created_by) REFERENCES users (id) ON DELETE RESTRICT,
    CONSTRAINT fk_companies_updated_by
        FOREIGN KEY (updated_by) REFERENCES users (id) ON DELETE RESTRICT
);

CREATE UNIQUE INDEX uq_companies_name_ci
    ON companies (lower(name));

COMMENT ON TABLE companies IS
    'Minimal company reference entity for internship registration (IF-DEC-21; Stage 3 scope addition).';

-- ---------------------------------------------------------------------------
-- internships
-- AS-01 working assumption: at most one REGISTERED internship per student.
-- ---------------------------------------------------------------------------
CREATE TABLE internships (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    student_user_id  BIGINT      NOT NULL,
    cohort_id        BIGINT      NOT NULL,
    company_id       BIGINT,
    start_date       DATE        NOT NULL,
    end_date         DATE        NOT NULL,
    title            TEXT,
    description      TEXT,
    lifecycle_state  TEXT        NOT NULL DEFAULT 'REGISTERED',
    created_at       TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at       TIMESTAMPTZ NOT NULL DEFAULT now(),
    created_by       BIGINT,
    CONSTRAINT fk_internships_student
        FOREIGN KEY (student_user_id) REFERENCES users (id) ON DELETE RESTRICT,
    CONSTRAINT fk_internships_cohort
        FOREIGN KEY (cohort_id) REFERENCES cohorts (id) ON DELETE RESTRICT,
    CONSTRAINT fk_internships_company
        FOREIGN KEY (company_id) REFERENCES companies (id) ON DELETE RESTRICT,
    CONSTRAINT fk_internships_created_by
        FOREIGN KEY (created_by) REFERENCES users (id) ON DELETE RESTRICT,
    CONSTRAINT ck_internships_dates
        CHECK (end_date >= start_date),
    CONSTRAINT ck_internships_lifecycle_state
        CHECK (lifecycle_state IN ('REGISTERED', 'VERIFIED_COMPLETE'))
);

CREATE UNIQUE INDEX uq_internships_active_student
    ON internships (student_user_id)
    WHERE lifecycle_state = 'REGISTERED';

CREATE INDEX ix_internships_cohort
    ON internships (cohort_id);

CREATE INDEX ix_internships_company
    ON internships (company_id);

COMMENT ON TABLE internships IS
    'Internship record anchored to one student and one cohort (FR-INT-001/002; DDD 4.6).';
COMMENT ON COLUMN internships.lifecycle_state IS
    'Interim anchor states only; the full state set remains OD-12.';
